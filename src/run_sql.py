"""Runs every '-- name:' block in sql/analysis.sql and writes results/sql_results.md."""
import os
import re
import sqlite3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "results")
os.makedirs(OUT, exist_ok=True)


def blocks(text):
    parts = re.split(r"^-- name: *(\S+)\s*$", text, flags=re.M)
    for i in range(1, len(parts), 2):
        body = parts[i + 1].strip()
        question = " ".join(l[2:].strip() for l in body.splitlines() if l.startswith("--"))
        yield parts[i], question, body


def md_table(cols, rows):
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join("" if v is None else str(v) for v in r) + " |")
    return "\n".join(out)


def main():
    con = sqlite3.connect(os.path.join(ROOT, "data", "darkstore.db"))
    sql = open(os.path.join(ROOT, "sql", "analysis.sql")).read()
    md = ["# SQL results\n", "Generated by `src/run_sql.py` from `sql/analysis.sql`. Data is simulated.\n"]
    for name, question, body in blocks(sql):
        cur = con.execute(body)
        cols = [c[0] for c in cur.description]
        rows = cur.fetchall()
        md += ["## %s\n" % name, "_%s_\n" % question, md_table(cols, rows), ""]
        print("\n== %s" % name)
        print(md_table(cols, rows))
    open(os.path.join(OUT, "sql_results.md"), "w").write("\n".join(md))


if __name__ == "__main__":
    main()
